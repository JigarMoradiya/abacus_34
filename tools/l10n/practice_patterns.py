#!/usr/bin/env python3
"""Practice page titles and descriptions: the server sends English text, the app translates it with a pattern map (module M22).

  practice_patterns.py <VedaaviAbacus.db> --write     read every page name / description of a synced app database, write
                                                      - English strings into res/values/strings.xml (block "practice patterns", names practice_<slug>)
                                                      - the Kotlin map  .../abacus_practice/PracticePatterns.kt  (normalized pattern -> R.string.id)
                                                      - the test fixture app/src/test/resources/practice_patterns.txt  (pattern <TAB> example)
                                                      - docs/l10n/translations/pending_m22_en.json for the translators (only keys without translation yet)
  practice_patterns.py <VedaaviAbacus.db> --check     list the patterns of the database that are NOT in the Kotlin map (exit 1 if any): run it after
                                                      the app synced new server data, then translate the new ones (re-run --write, translate, apply.py)
  practice_patterns.py --verify                        every translation keeps the same number of %k$s placeholders as the English (exit 1 if not)
  practice_patterns.py --bidi                          keep the signs of the numbers in the Arabic texts left to right (LRE ... PDF around "+%1$s,+%2$s", "(+-)", "%1$sD x %2$sD")

A pattern is the text with its whitespace collapsed, lower-cased and every number replaced by '#': "Mental Arithmetic 12" -> "mental arithmetic #".
Texts without any letter ("+5", "-3,-4", "+-") are the same in every language and are not in the map.
A database file comes from a debug build that synced (adb run-as ... cat databases/VedaaviAbacus.db, plus its -wal and -shm files).
"""
import collections, json, os, re, sqlite3, sys

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
RES = os.path.join(BASE, 'app', 'src', 'main', 'res')
KT = os.path.join(BASE, 'app', 'src', 'main', 'java', 'com', 'jigar', 'me', 'ui', 'view', 'home', 'screens', 'abacus_practice', 'PracticePatterns.kt')
FIXTURE = os.path.join(BASE, 'app', 'src', 'test', 'resources', 'practice_patterns.txt')
PENDING = os.path.join(BASE, 'docs', 'l10n', 'translations', 'pending_m22_en.json')
BEGIN, END = '    <!-- practice patterns (generated by tools/l10n/practice_patterns.py, do not edit by hand) -->\n', '    <!-- end practice patterns -->\n'

def collapse(t): return re.sub(r'\s+', ' ', (t or '').strip())
def pattern_of(t): return re.sub(r'\d+', '#', collapse(t)).lower()
def has_letters(p): return re.search(r'[a-z]', p) is not None

def slug(p):
    s = p.replace('+', ' plus ').replace('-', ' minus ').replace('&', ' and ').replace('#', ' n ')
    return 'practice_' + re.sub(r'[^a-z0-9]+', '_', s).strip('_')

def read_patterns(db):
    """{pattern: (english with %k$s, example text)} for every page name and description of the database."""
    seen = collections.defaultdict(collections.Counter)
    for name, description in sqlite3.connect(db).execute('select name, description from pages'):
        for text in (name, description):
            text = collapse(text)
            if text and has_letters(pattern_of(text)): seen[pattern_of(text)][text] += 1
    out = {}
    for p, variants in seen.items():
        best = max(variants.items(), key=lambda kv: (kv[1], sum(c.isupper() for c in kv[0])))[0]   # most common, ties: more capitals
        count = iter(range(1, 100))
        out[p] = (re.sub(r'\d+', lambda m: '%%%d$s' % next(count), best), best)
    return out

def esc(t): return t.replace('&', '&amp;').replace("'", "\\'").replace('<', '&lt;')

def kotlin_map():
    if not os.path.exists(KT): return {}
    return dict(re.findall(r'"([^"]+)" to R\.string\.([a-z0-9_]+)', open(KT, encoding='utf-8').read()))

def write(db):
    pats = read_patterns(db)
    names = {}
    for p in sorted(pats):
        n = slug(p)
        assert n not in names, ('slug clash', n, p, names[n]); names[n] = p
    # 1. English strings
    xml_path = os.path.join(RES, 'values', 'strings.xml')
    xml = open(xml_path, encoding='utf-8').read()
    block = BEGIN + ''.join(f'    <string name="{slug(p)}">{esc(pats[p][0])}</string>\n' for p in sorted(pats)) + END
    if BEGIN in xml: xml = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), lambda m: block, xml, flags=re.S)
    else: xml = xml.replace('</resources>', block + '</resources>')
    open(xml_path, 'w', encoding='utf-8').write(xml)
    # 2. Kotlin map
    lines = ''.join(f'        "{p}" to R.string.{slug(p)},\n' for p in sorted(pats))
    open(KT, 'w', encoding='utf-8').write(
        'package com.jigar.me.ui.view.home.screens.abacus_practice\n\nimport com.jigar.me.R\n\n'
        '/** Generated by tools/l10n/practice_patterns.py from the server data (page titles and descriptions): do not edit by hand. */\n'
        'internal object PracticePatterns {\n    /** normalized pattern (see [PracticeText.patternOf]) -> the translated text with %1$s, %2$s ... for the numbers. */\n'
        '    val map: Map<String, Int> = mapOf(\n' + lines + '    )\n}\n')
    # 3. test fixture
    os.makedirs(os.path.dirname(FIXTURE), exist_ok=True)
    open(FIXTURE, 'w', encoding='utf-8').write(''.join(f'{p}\t{pats[p][1]}\n' for p in sorted(pats)))
    # 4. English master for the translators (keys that have no translation yet)
    have = set()
    tdir = os.path.dirname(PENDING)
    for f in os.listdir(tdir):
        if f.endswith('.json') and not f.startswith('pending_'): have |= set(json.load(open(os.path.join(tdir, f), encoding='utf-8')))
    strings = {slug(p): pats[p][0] for p in sorted(pats) if slug(p) not in have}
    json.dump({'strings': strings, 'plurals': {}}, open(PENDING, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'{len(pats)} patterns written; {len(strings)} still to translate -> {os.path.relpath(PENDING, BASE)}')

def check(db):
    known = set(kotlin_map())
    missing = sorted(p for p in read_patterns(db) if p not in known)
    for p in missing: print('not translated:', p)
    print(len(missing), 'patterns missing from PracticePatterns.kt')
    sys.exit(1 if missing else 0)

LRE, PDF = '\u202a', '\u202c'
_ATOM = r'(?:[x\u00d7]\s*)?[+\-\u2212]{0,2}%\d\$s(?:D)?'
_RUN = re.compile(_ATOM + r'(?:(?:\s*,\s*|\s*[x\u00d7]\s*|(?=[+\-\u2212]))' + _ATOM + r')*')
_SIGNS = re.compile(r'\(([+\-\u2212]{1,2})\)')

def bidi_text(t):
    """Arabic text with its number fragments and sign groups wrapped in LRE ... PDF (idempotent)."""
    def wrap(m): return t_wrap(m.group(0))
    def t_wrap(x): return x if re.fullmatch(r'%\d\$s', x) else LRE + x + PDF   # a bare number needs no mark
    t = re.sub(r'(?<!' + LRE + r')' + _RUN.pattern, wrap, t)
    return _SIGNS.sub(lambda m: '(' + LRE + m.group(1) + PDF + ')' if LRE not in m.group(0) else m.group(0), t)

def bidi():
    path = os.path.join(BASE, 'docs', 'l10n', 'translations', 'm22_practice.json')
    data = json.load(open(path, encoding='utf-8')); n = 0
    for key, entry in data.items():
        if 'ar' in entry:
            new = bidi_text(entry['ar'].replace(LRE, '').replace(PDF, ''))
            if new != entry['ar']: entry['ar'] = new; n += 1
    json.dump(data, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(n, 'Arabic texts changed')

def verify():
    import glob
    import xml.etree.ElementTree as ET
    ph = lambda t: sorted(re.findall(r'%\d+\$s', t or ''))
    english = {el.get('name'): el.text for el in ET.parse(os.path.join(RES, 'values', 'strings.xml')).getroot() if el.get('name', '').startswith('practice_')}
    bad = 0
    for path in sorted(glob.glob(os.path.join(RES, 'values-*', 'strings.xml'))):
        for el in ET.parse(path).getroot():
            n = el.get('name', '')
            if n in english and ph(el.text) != ph(english[n]):
                print(os.path.basename(os.path.dirname(path)), n, ph(el.text), 'vs', ph(english[n])); bad += 1
    print('placeholder mismatches:', bad)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    a = sys.argv[1:]
    if '--verify' in a: verify()
    if '--bidi' in a: bidi(); sys.exit(0)
    db = next((x for x in a if not x.startswith('--')), None)
    if not db: print(__doc__); sys.exit(2)
    if '--write' in a: write(db)
    elif '--check' in a: check(db)
    else: print(__doc__)
